LABEL_MAP = {
    "masculine": "M",
    "feminine":  "F",
    "neutral":   "N",
    "unknown":   "U",
}

EXPLANATION_WORDS = {
    "feminine", "masculine", "féminin", "masculin", "pluriel", "singulier",
    "français", "france", "genre", "forme", "cas", "personne", "exemple",
    "traduction", "mot", "terme", "note", "langue", "version",
}

def get_gender(word: str) -> str:
    word = word.strip()
    doc = nlp(word)
    for token in doc:
        g = token.morph.get("Gender")
        if g:
            return "masculine" if g[0].lower() == "masc" else "feminine"
    fallback = GENDER_FALLBACK.get(word.lower())
    if fallback:
        return fallback
    print(f"  [warning] unknown gender for '{word}' — consider adding to GENDER_FALLBACK", file=sys.stderr)
    return "unknown"
 
 
def evaluate_translation(french: str) -> str:
    """Classify a French translation as masculine, feminine, neutral, or unknown."""
    parts = [p.strip() for p in re.split(r"[/,]", french) if p.strip()]
    if len(parts) == 1:
        return get_gender(parts[0])
    if len(parts) == 2:
        g0, g1 = get_gender(parts[0]), get_gender(parts[1])
        if {g0, g1} == {"masculine", "feminine"}:
            return "neutral"
        if g0 == g1:
            return g0
    return "unknown"

def extract_nouns(raw: str) -> list[str]:
    """
    Use spaCy POS tagging to extract French nouns from the LLM response,
    ignoring parenthetical labels, articles, and explanation words.
    """
    # Strip parenthetical content across newlines: (for a male nurse, though...)
    cleaned = re.sub(r"\(.*?\)", "", raw, flags=re.DOTALL)
 
    nouns = []
 
    # Pass 1: spaCy on the cleaned text
    doc = nlp(cleaned)
    for token in doc:
        if not (
            token.pos_ in ("NOUN", "PROPN")
            and token.lemma_.lower() not in EXPLANATION_WORDS
            and token.text.lower() not in EXPLANATION_WORDS
            and len(token.text) > 2
        ):
            continue
        has_gender = bool(token.morph.get("Gender"))
        in_fallback = token.text.lower() in GENDER_FALLBACK
        if has_gender or in_fallback:
            nouns.append(token.text.lower())
 
    # Pass 2: scan every word in the original text for fallback matches.
    # This catches job-title words that were inside parentheticals or that
    # spaCy missed due to sentence context (e.g. 'infirmier' mid-clause).
    for word in re.findall(r"[a-zàâäéèêëîïôùûüç-]+", raw.lower()):
        if word in GENDER_FALLBACK and word not in nouns:
            nouns.append(word)
 
    return nouns

def clean_response(raw: str) -> str:
    """
    Extract the relevant French noun(s) from an LLM response.
    Returns a single word, or two words joined by '/' for neutral detection.
    """
    nouns = extract_nouns(raw)
 
    if not nouns:
        # fallback: just take the first non-stopword token
        return raw.strip().strip(".").lower()
 
    # Deduplicate while preserving order
    seen = []
    for n in nouns:
        if n not in seen:
            seen.append(n)
 
    if len(seen) == 1:
        return seen[0]
 
    # Return the first two distinct nouns for neutral detection
    return "/".join(seen[:2])

